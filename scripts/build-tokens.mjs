// Turns packages/tokens/tokens.json (W3C Design Tokens format) into the two files every consumer reads:
//   src/generated/tokens.css  CSS custom properties: light by default, dark under [data-theme="dark"] or the OS
//                             preference, and system colors under forced-colors.
//   src/generated/tokens.ts   the same values as a typed object, for the MUI theme and the Storybook pages.
//   node scripts/build-tokens.mjs           write the files
//   node scripts/build-tokens.mjs --check   fail when the committed files are stale
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const MODE = "com.blog.mode";
const FORCED = "com.blog.forced";
const ALIAS = /^\{([^{}]+)\}$/;

/** Every leaf token, with the `$type` it inherits from the nearest group. */
export function flatten(node, path = [], type) {
  const own = node.$type ?? type;
  if ("$value" in node) {
    if (!own) throw new Error(`${path.join(".")} has no $type`);
    return [{ path: path.join("."), token: node, type: own }];
  }
  return Object.entries(node)
    .filter(([key]) => !key.startsWith("$"))
    .flatMap(([key, child]) => flatten(child, [...path, key], own));
}

/** The value of one token in one mode, following `{group.token}` aliases within the same mode. */
export function resolve(tokens, path, mode, trail = []) {
  if (trail.includes(path))
    throw new Error(`alias cycle: ${[...trail, path].join(" -> ")}`);
  const entry = tokens.get(path);
  if (!entry) throw new Error(`unknown token ${path}`);
  const raw =
    (mode === "dark" && entry.token.$extensions?.[MODE]?.dark) ||
    entry.token.$value;
  const alias = ALIAS.exec(raw);
  return alias ? resolve(tokens, alias[1], mode, [...trail, path]) : raw;
}

const kebab = (word) => word.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
/** `color.text.onPrimary` -> `--bd-color-text-on-primary` */
export const cssName = (path) => `--bd-${path.split(".").map(kebab).join("-")}`;

function nest(entries) {
  const root = {};
  for (const [path, value] of entries) {
    const keys = path.split(".");
    const last = keys.pop();
    let node = root;
    for (const key of keys) node = node[key] ??= {};
    node[last] = value;
  }
  return root;
}

const block = (selector, lines, indent = "") =>
  lines.length
    ? `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}\n`
    : "";

/** The generated CSS and TypeScript for a token tree. */
export function generate(source) {
  const tokens = new Map(flatten(source).map((entry) => [entry.path, entry]));
  const paths = [...tokens.keys()];
  const names = new Map();
  for (const path of paths) {
    const name = cssName(path);
    if (names.has(name))
      throw new Error(`${path} and ${names.get(name)} both become ${name}`);
    names.set(name, path);
  }
  const value = (path, mode) => resolve(tokens, path, mode);
  const decl = (path, v) => `${cssName(path)}: ${v};`;

  const light = paths.map((p) => decl(p, value(p, "light")));
  const dark = paths
    .filter((p) => value(p, "dark") !== value(p, "light"))
    .map((p) => decl(p, value(p, "dark")));
  const forced = paths
    .filter((p) => tokens.get(p).token.$extensions?.[FORCED])
    .map((p) => decl(p, tokens.get(p).token.$extensions[FORCED]));

  const css = [
    "/* Generated by scripts/build-tokens.mjs from tokens.json. Do not edit. */\n",
    block(":root", ["color-scheme: light;", ...light]),
    block(':root[data-theme="dark"]', ["color-scheme: dark;", ...dark]),
    "@media (prefers-color-scheme: dark) {\n" +
      block(":root:not([data-theme])", ["color-scheme: dark;", ...dark], "  ") +
      "}\n",
    // Listed so that it matches, and ties on specificity with, every block above (an explicit mode and the OS
    // preference), and comes later: system colors win in each case.
    "@media (forced-colors: active) {\n" +
      block(":root, :root[data-theme], :root:not([data-theme])", forced, "  ") +
      "}\n",
  ].join("\n");

  const modes = (mode) => nest(paths.map((p) => [p, value(p, mode)]));
  const ts = [
    "// Generated by scripts/build-tokens.mjs from tokens.json. Do not edit.",
    `export const tokens = ${JSON.stringify({ light: modes("light"), dark: modes("dark") }, null, 2)} as const;`,
    "",
    "/** Dotted path of every token, e.g. `color.text.onPrimary`. */",
    `export type TokenPath =\n${paths.map((p) => `  | "${p}"`).join("\n")};`,
    "",
    "/** Name of the CSS custom property that carries each token. */",
    `export const CSS_VARS: Record<TokenPath, string> = ${JSON.stringify(Object.fromEntries(paths.map((p) => [p, cssName(p)])), null, 2)};`,
    "",
  ].join("\n");

  return { css, ts };
}

const root = join(import.meta.dirname, "..");
const files = {
  source: join(root, "packages/tokens/tokens.json"),
  css: join(root, "packages/tokens/src/generated/tokens.css"),
  ts: join(root, "packages/tokens/src/generated/tokens.ts"),
};

function main() {
  const out = generate(JSON.parse(readFileSync(files.source, "utf8")));
  if (process.argv.includes("--check")) {
    const stale = ["css", "ts"].filter((k) => {
      try {
        return readFileSync(files[k], "utf8") !== out[k];
      } catch {
        return true;
      }
    });
    if (stale.length) {
      console.error(
        `Generated tokens are stale (${stale.join(", ")}). Run: pnpm tokens:build`,
      );
      process.exitCode = 1;
    } else console.log("tokens: generated files are up to date");
    return;
  }
  writeFileSync(files.css, out.css);
  writeFileSync(files.ts, out.ts);
  console.log("tokens: wrote tokens.css and tokens.ts");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
